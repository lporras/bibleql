# frozen_string_literal: true

module Mutations
  class RegisterInstallation < BaseMutation
    description "Registers a client app installation and returns a new API token for it. " \
      "Send without an Authorization header. Registering the same installationId again revokes " \
      "its previous token and issues a new one; existing tokens are never returned. " \
      "Rate limited to 10 per hour per IP."

    argument :installation_id, ID, required: true,
      description: "UUID generated by the client on first launch and kept in secure storage"
    argument :platform, Types::PlatformEnum, required: true,
      description: "Operating system the installation runs on"
    argument :app_version, String, required: true,
      description: "Client app version (e.g. '1.4.0'); letters, digits and . + - only, max 32 characters"

    field :token, String, null: false,
      description: "The new API token. Shown only once: store it securely and send it as `Authorization: Bearer <token>`"
    field :installation_id, ID, null: false,
      description: "The registered installation's UUID"
    field :daily_limit, Integer, null: false,
      description: "Requests per day allowed for this token"

    def resolve(installation_id:, platform:, app_version:)
      api_key = InstallationRegistrar.call(installation_id: installation_id, platform: platform, app_version: app_version)

      { token: api_key.token, installation_id: api_key.installation.installation_id, daily_limit: api_key.daily_limit }
    rescue ActiveRecord::RecordInvalid => e
      raise GraphQL::ExecutionError.new(e.record.errors.full_messages.to_sentence, extensions: { "code" => "INVALID_INPUT" })
    rescue InstallationRegistrar::Revoked => e
      raise GraphQL::ExecutionError.new(e.message, extensions: { "code" => "INSTALLATION_REVOKED" })
    end
  end
end
